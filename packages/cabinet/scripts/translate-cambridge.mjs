// Regenerate the as7 translations of the 1972 Cambridge sources. Each must assemble with as7 to the
// Cambridge image word for word, or nothing is written.
import { readFileSync, writeFileSync } from "node:fs";
import { cambridgeToAs7 } from "../dist/asm/cambridge-as7.js";

const tapes = new URL("../tapes/", import.meta.url);
const jobs = [
	{ from: "symelec/rsppix.asm", to: "pdp7forth/rsppix.s", prefix: "r" },
	{ from: "symelec/symelec.asm", to: "symelec/symelec.s", prefix: "s" },
];
for (const { from, to, prefix } of jobs) {
	const name = from.split("/").at(-1);
	const r = cambridgeToAs7([{ name, text: readFileSync(new URL(from, tapes), "utf8") }], { prefix });
	if (r.mismatches.length) throw new Error(`${name}:\n${r.mismatches.slice(0, 20).join("\n")}`);
	const header = `" ${name}, Cambridge 1972, in as7: generated by scripts/translate-cambridge.mjs, do not edit.\n`;
	writeFileSync(new URL(to, tapes), header + r.text);
	console.log(`${to}: ${r.as7.words.length} words, identical to Cambridge${r.numeric.length ? `; numeric at ${r.numeric.join(" ")}` : ""}`);
}
