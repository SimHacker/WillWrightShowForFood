export const APPLE2_SYMBOLS: readonly Symbol65[] = [
	...LIST.map(([name, addr]) => ({ name, addr })),
	...Array.from({ length: PANEL_BYTES }, (_, i) => ({ name: i ? `PANEL+${i}` : "PANEL", addr: PANEL_BASE + i })),
];

const BY_ADDR = new Map(APPLE2_SYMBOLS.map((s) => [s.addr, s.name]));

/** The name of `addr`, or "" when it has none. */
export const apple2Name = (addr: number): string => BY_ADDR.get(addr & 0xffff) ?? "";
